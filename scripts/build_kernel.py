"""把 scripts/ 的四个源文件内联成 Kaggle script kernel（阶段 A）。

生成顺序按拓扑序：schema → presets → data_split → train_full。
生成规则是确定性的：删除跨模块 `from X import ...` 行；前三份删除
`if __name__ == "__main__":` 及其后全部内容；train_full 的守卫保留。

子命令：
  （无参数）         生成正式版 kaggle/flower/kernel.py
  --modes a,b --smoke  生成冒烟版 kaggle/flower-smoke/kernel.py（不覆盖正式版）
  --check            复核磁盘 kernel.py 与当前源文件的一致性（provenance 掩码）
  --selfcheck-embed  解码内嵌 meta.csv 并输出字节数
  --check-symbols    六项 AST 契约检查
  --selftest-symbols 反向 fixture：函数体内注入 ImportFrom 必被拒绝
  --print-source-sha 输出四源文件组合 SHA-256
"""

import argparse
import ast
import base64
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zlib
from datetime import datetime, timezone
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parent
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

import schema  # noqa: E402 - 需要 scripts/ 在 sys.path 上

KAGGLE_DIR = ROOT / "kaggle" / "flower"
SMOKE_DIR = ROOT / "kaggle" / "flower-smoke"
FORMAL_KERNEL = KAGGLE_DIR / "kernel.py"
SMOKE_KERNEL = SMOKE_DIR / "kernel.py"
FORMAL_METADATA = KAGGLE_DIR / "kernel-metadata.json"
SMOKE_METADATA = SMOKE_DIR / "kernel-metadata.json"
META_CSV = ROOT / "data" / "meta.csv"
KERNEL_REF = "feisama/flower-102-transfer"
SMOKE_KERNEL_REF = "feisama/flower-102-smoke"
SMOKE_TITLE = "Flower 102 Smoke"

SOURCE_ORDER = ("schema", "presets", "data_split", "train_full")
CROSS_MODULES = ("schema", "presets", "data_split")
REQUIRED_SYMBOLS = ("METRICS_FIELDS", "PRESETS", "build_split", "train_epoch", "main")

EMBED_SENTINEL = "# @@KERNEL_EMBED@@"
BEGIN = "# @@PROVENANCE_BEGIN@@"
END = "# @@PROVENANCE_END@@"
PLACEHOLDER = "# @@PROVENANCE_MASK@@"

_GUARD_RE = re.compile(r"^if __name__ == ['\"]__main__['\"]:")
_IMPORT_RE = re.compile(r"^from (schema|presets|data_split) import ")
_SOURCE_SHA_RE = re.compile(r'^_KERNEL_SOURCE_SHA256 = "([0-9a-f]{64})"$', re.M)
_META_B85_RE = re.compile(r'^_KERNEL_META_B85 = "([^"]*)"$', re.M)


def _fail(message):
    print(f"build_kernel: {message}", file=sys.stderr)
    raise SystemExit(1)


def _sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def _source_paths():
    return {
        "schema": SCRIPTS / "schema.py",
        "presets": SCRIPTS / "presets.py",
        "data_split": SCRIPTS / "data_split.py",
        "train_full": SCRIPTS / "train_full.py",
    }


def _source_texts():
    texts = {}
    for name, path in _source_paths().items():
        texts[name] = path.read_text(encoding="utf-8")
    return texts


def _strip_module(text, drop_guard):
    lines = []
    for line in text.splitlines():
        if _IMPORT_RE.match(line):
            continue
        if drop_guard and _GUARD_RE.match(line):
            break
        lines.append(line)
    return "\n".join(lines).rstrip() + "\n"


def _now_iso():
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def _git_state():
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        ).stdout.strip()
        status = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        ).stdout
        return commit or None, bool(status.strip())
    except (OSError, subprocess.SubprocessError):
        return None, None


def _embed_block(modes, smoke, source_sha, meta_path):
    raw = Path(meta_path).read_bytes()
    digest = _sha256_bytes(raw)
    if digest != schema.META_SHA256:
        _fail(f"data/meta.csv sha256 不符: {digest} != {schema.META_SHA256}")
    encoded = base64.b85encode(zlib.compress(raw, 9)).decode("ascii")
    commit, dirty = _git_state()
    provenance = {
        "git_commit": commit,
        "git_dirty": dirty,
        "built_at": _now_iso(),
    }
    lines = [
        f"_KERNEL_MODES = {json.dumps(list(modes))}",
        f"_KERNEL_SMOKE = {bool(smoke)}",
        f"_KERNEL_REF = {json.dumps(SMOKE_KERNEL_REF if smoke else KERNEL_REF)}",
        f'_KERNEL_META_B85 = "{encoded}"',
        BEGIN,
        f"_KERNEL_PROVENANCE = {provenance!r}",
        END,
        f'_KERNEL_SOURCE_SHA256 = "{source_sha}"',
    ]
    return "\n".join(lines) + "\n", raw


def generate_text(modes, smoke, meta_path=META_CSV):
    texts = _source_texts()
    source_sha = schema.source_sha256(ROOT)
    per_file = {
        name: _sha256_bytes((_source_paths()[name]).read_bytes())
        for name in SOURCE_ORDER
    }
    header = [
        "# GENERATED BY scripts/build_kernel.py — DO NOT EDIT",
        (
            "# source sha256 "
            f"schema={per_file['schema']} presets={per_file['presets']} "
            f"data_split={per_file['data_split']} train_full={per_file['train_full']}"
        ),
        "",
    ]

    parts = ["\n".join(header)]
    for name in ("schema", "presets", "data_split"):
        parts.append(f"# ==== from scripts/{name}.py ====")
        parts.append(_strip_module(texts[name], drop_guard=True))

    parts.append("# ==== from scripts/train_full.py ====")
    train_body = _strip_module(texts["train_full"], drop_guard=False)
    embed, _raw = _embed_block(modes, smoke, source_sha, meta_path)
    if train_body.count(EMBED_SENTINEL) != 1:
        _fail("train_full.py 必须恰含一处 # @@KERNEL_EMBED@@ 哨兵")
    train_body = train_body.replace(EMBED_SENTINEL, embed.rstrip("\n"))
    parts.append(train_body)

    text = "\n".join(part.rstrip("\n") for part in parts) + "\n"
    try:
        compile(text, str(FORMAL_KERNEL), "exec")
    except SyntaxError as exc:
        _fail(f"生成结果语法错误: {exc}")
    return text


def mask_provenance(text):
    """把 provenance 块整段替换成固定占位符（按行定位，不跨行贪婪）。"""
    if text.count(BEGIN) != 1:
        raise ValueError(f"{BEGIN} 必须恰出现 1 次")
    if text.count(END) != 1:
        raise ValueError(f"{END} 必须恰出现 1 次")
    payload = [
        line for line in text.splitlines() if line.startswith("_KERNEL_PROVENANCE = ")
    ]
    if len(payload) != 1:
        raise ValueError("_KERNEL_PROVENANCE 标记行必须恰出现 1 次")

    output = []
    inside = False
    for line in text.splitlines(keepends=True):
        stripped = line.rstrip("\n")
        if stripped == BEGIN:
            if inside:
                raise ValueError("provenance 块嵌套")
            inside = True
            output.append(PLACEHOLDER + "\n")
            continue
        if inside:
            if stripped == END:
                inside = False
            continue
        if stripped == END:
            raise ValueError("provenance END 出现在 BEGIN 之前")
        output.append(line)
    if inside:
        raise ValueError("provenance 块未闭合")
    return "".join(output)


def _module_scope_names(tree):
    names = set()

    def add_target(target):
        if isinstance(target, ast.Name):
            names.add(target.id)
        elif isinstance(target, (ast.Tuple, ast.List)):
            for element in target.elts:
                add_target(element)
        elif isinstance(target, ast.Starred):
            add_target(target.value)

    def walk_body(body):
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                names.add(node.name)
            elif isinstance(node, ast.Assign):
                for target in node.targets:
                    add_target(target)
            elif isinstance(node, ast.AnnAssign):
                add_target(node.target)
            elif isinstance(node, (ast.If, ast.For, ast.AsyncFor, ast.While, ast.Try, ast.With, ast.AsyncWith)):
                walk_body(node.body)
                walk_body(getattr(node, "orelse", []) or [])
                walk_body(getattr(node, "finalbody", []) or [])
                for handler in getattr(node, "handlers", []) or []:
                    walk_body(handler.body)

    walk_body(tree.body)
    return names


def check_kernel_ast(path):
    """生成 kernel 的六项 AST 契约检查；返回违规码列表（空=通过）。"""
    path = Path(path)
    violations = []
    try:
        source = path.read_text(encoding="utf-8")
    except OSError as exc:
        return [f"E_SYNTAX:{exc}"]
    try:
        tree = ast.parse(source)
        compile(source, str(path), "exec")
    except SyntaxError as exc:
        return [f"E_SYNTAX:{exc.msg}"]

    # 1) 模块作用域符号
    names = _module_scope_names(tree)
    for symbol in REQUIRED_SYMBOLS:
        if symbol not in names:
            violations.append(f"E_SYMBOL:{symbol}")

    # 2) 跨模块 import（全树）
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                root = alias.name.split(".")[0]
                if root in CROSS_MODULES:
                    violations.append(f"E_IMPORT:{alias.name}")
        elif isinstance(node, ast.ImportFrom):
            if node.module in CROSS_MODULES:
                violations.append(f"E_IMPORTFROM:{node.module}")
            if node.level > 0:
                for alias in node.names:
                    if alias.name in CROSS_MODULES:
                        violations.append(f"E_IMPORTFROM:{alias.name}")

    # 3) 跨模块属性访问（仅限三个模块名）
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Attribute)
            and isinstance(node.value, ast.Name)
            and node.value.id in CROSS_MODULES
        ):
            violations.append(f"E_ATTR:{node.value.id}")

    # 4/5) __main__ 守卫
    guards = []
    for node in tree.body:
        if not isinstance(node, ast.If):
            continue
        test = node.test
        if (
            isinstance(test, ast.Compare)
            and len(test.ops) == 1
            and isinstance(test.ops[0], ast.Eq)
            and isinstance(test.left, ast.Name)
            and test.left.id == "__name__"
            and len(test.comparators) == 1
            and isinstance(test.comparators[0], ast.Constant)
            and test.comparators[0].value == "__main__"
        ):
            guards.append(node)
    if len(guards) != 1:
        violations.append(f"E_GUARD_COUNT:{len(guards)}")
    else:
        has_main = any(
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id == "main"
            for node in ast.walk(guards[0])
        )
        if not has_main:
            violations.append("E_GUARD_NO_MAIN")

    return violations


def _guard_count(path):
    tree = ast.parse(Path(path).read_text(encoding="utf-8"))
    count = 0
    for node in tree.body:
        test = getattr(node, "test", None)
        if (
            isinstance(node, ast.If)
            and isinstance(test, ast.Compare)
            and isinstance(test.left, ast.Name)
            and test.left.id == "__name__"
            and len(test.comparators) == 1
            and isinstance(test.comparators[0], ast.Constant)
            and test.comparators[0].value == "__main__"
        ):
            count += 1
    return count


def _write_kernel(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    violations = check_kernel_ast(path)
    if violations:
        for item in violations:
            print(f"build_kernel FAIL: {item}", file=sys.stderr)
        return 1
    print(f"wrote {path.relative_to(ROOT)}")
    return 0


def _write_smoke_metadata():
    """冒烟变体使用独立 slug，避免覆盖正式 kernel。"""
    payload = {
        "id": SMOKE_KERNEL_REF,
        "title": SMOKE_TITLE,
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_internet": True,
        "dataset_sources": ["trnglbotrn/oxford-102-flowers"],
        "competition_sources": [],
        "kernel_sources": [],
    }
    path = SMOKE_METADATA
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def _check(path):
    path = Path(path)
    if not path.is_file():
        _fail(f"kernel 不存在: {path}")
    disk = path.read_text(encoding="utf-8")
    try:
        disk_masked = mask_provenance(disk)
    except ValueError as exc:
        _fail(f"provenance 掩码失败: {exc}")

    expected = generate_text(schema.CANONICAL_MODES, False)
    expected_masked = mask_provenance(expected)
    disk_digest = _sha256_bytes(disk_masked.encode("utf-8"))
    expected_digest = _sha256_bytes(expected_masked.encode("utf-8"))
    if disk_digest != expected_digest:
        print(
            "build_kernel FAIL: kernel.py 与源文件不一致 "
            f"(masked sha256 {disk_digest} != {expected_digest})",
            file=sys.stderr,
        )
        return 1

    match = _SOURCE_SHA_RE.search(disk)
    if not match:
        print("build_kernel FAIL: 缺少 _KERNEL_SOURCE_SHA256 行", file=sys.stderr)
        return 1
    current = schema.source_sha256(ROOT)
    if match.group(1) != current:
        print(
            f"build_kernel FAIL: _KERNEL_SOURCE_SHA256={match.group(1)} != {current}",
            file=sys.stderr,
        )
        return 1
    print("kernel check ok")
    return 0


def _selfcheck_embed(path):
    path = Path(path)
    if not path.is_file():
        _fail(f"kernel 不存在: {path}")
    text = path.read_text(encoding="utf-8")
    match = _META_B85_RE.search(text)
    if not match:
        _fail("kernel.py 中缺少 _KERNEL_META_B85")
    raw = zlib.decompress(base64.b85decode(match.group(1).encode("ascii")))
    digest = _sha256_bytes(raw)
    if digest != schema.META_SHA256:
        _fail(f"内嵌 meta.csv sha256 不符: {digest}")
    print(f"{len(raw)} bytes")
    return 0


def _selftest_symbols(path):
    source = Path(path).read_text(encoding="utf-8")
    marker = "def now_iso():"
    if marker not in source:
        _fail("反向 fixture 失败：找不到 now_iso 函数")
    injected = source.replace(
        marker, marker + "\n    from schema import SCHEMA_VERSION", 1
    )
    base = Path("/tmp/opencode")
    base.mkdir(parents=True, exist_ok=True)
    temp_dir = Path(tempfile.mkdtemp(prefix="kernel_symbols_", dir=str(base)))
    fixture = temp_dir / "kernel_fixture.py"
    try:
        fixture.write_text(injected, encoding="utf-8")
        violations = check_kernel_ast(fixture)
        if "E_IMPORTFROM:schema" not in violations:
            print(
                f"build_kernel FAIL: 反向 fixture 未检出 E_IMPORTFROM:schema，"
                f"实际 {violations}",
                file=sys.stderr,
            )
            return 1
        print("reverse fixture ok: E_IMPORTFROM:schema")
        return 0
    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


def _check_symbols(path):
    violations = check_kernel_ast(path)
    if violations:
        for item in violations:
            print(f"build_kernel FAIL: {item}", file=sys.stderr)
        return 1
    imports = 0
    importfroms = 0
    attrs = 0
    # 计数只用于展示；违规判定完全来自 check_kernel_ast。
    tree = ast.parse(Path(path).read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            if any(alias.name.split(".")[0] in CROSS_MODULES for alias in node.names):
                imports += 1
        elif isinstance(node, ast.ImportFrom):
            if node.module in CROSS_MODULES:
                importfroms += 1
            elif node.level > 0 and any(
                alias.name in CROSS_MODULES for alias in node.names
            ):
                importfroms += 1
        elif (
            isinstance(node, ast.Attribute)
            and isinstance(node.value, ast.Name)
            and node.value.id in CROSS_MODULES
        ):
            attrs += 1
    guards = _guard_count(path)
    entry = "main()"
    print(
        "symbols ok: METRICS_FIELDS PRESETS build_split train_epoch main; "
        f"imports={imports}; importfroms={importfroms}; attr_refs={attrs}; "
        f"guards={guards}; entry={entry}"
    )
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description="生成/校验 Kaggle kernel")
    parser.add_argument("--modes", default="", help="逗号分隔的 mode 子集")
    parser.add_argument("--smoke", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--selfcheck-embed", action="store_true")
    parser.add_argument("--check-symbols", action="store_true")
    parser.add_argument("--selftest-symbols", action="store_true")
    parser.add_argument("--print-source-sha", action="store_true")
    parser.add_argument("--kernel", default=str(FORMAL_KERNEL))
    args = parser.parse_args(argv)

    if args.print_source_sha:
        print(schema.source_sha256(ROOT))
        return 0
    if args.check:
        return _check(Path(args.kernel))
    if args.selfcheck_embed:
        return _selfcheck_embed(Path(args.kernel))
    if args.selftest_symbols:
        return _selftest_symbols(Path(args.kernel))
    if args.check_symbols:
        return _check_symbols(Path(args.kernel))

    modes = list(schema.CANONICAL_MODES)
    if args.modes:
        modes = [item.strip() for item in args.modes.split(",") if item.strip()]
        unknown = [item for item in modes if item not in schema.CANONICAL_MODES]
        if unknown:
            _fail(f"未知 mode: {unknown}")
    smoke_variant = bool(
        args.smoke or (args.modes and modes != list(schema.CANONICAL_MODES))
    )
    text = generate_text(modes, smoke_variant)
    destination = SMOKE_KERNEL if smoke_variant else FORMAL_KERNEL
    code = _write_kernel(destination, text)
    if code != 0:
        return code
    if smoke_variant:
        _write_smoke_metadata()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
